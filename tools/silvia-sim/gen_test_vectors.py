"""Turns the logged shots (data/shot*.jsonl, 1 Hz) into a C header for the native
brew-detection test: sensor readings sample-and-hold resampled to the firmware's 400 ms
interval, in 1/10 °C, plus the start time of every water draw.

    python3 gen_test_vectors.py > ../../test/test_brew_detection/recorded_shots.h
"""
import sys
from pathlib import Path

from test_brew_detection import SAMPLE_S, load, shot_starts

HERE = Path(__file__).parent


def main():
    out = ["// generated by tools/silvia-sim/gen_test_vectors.py - do not edit", "#pragma once", "",
           "struct RecordedShot {", "    const char *name;", "    const short *tenths;  // one reading every 400 ms",
           "    int count;", "    const int *drawStartsMs;", "    int drawCount;", "};", ""]
    entries = []
    for path in sorted((HERE / "data").glob("shot*.jsonl")):
        series = load(path)
        starts = shot_starts(series)
        samples = []
        j = 0
        t = 0.0
        while t <= series[-1][0]:
            while j + 1 < len(series) and series[j + 1][0] <= t:
                j += 1
            samples.append(round(series[j][1] * 10))
            t += SAMPLE_S
        name = path.stem
        out.append(f"static const short {name}Tenths[] = {{")
        for i in range(0, len(samples), 20):
            out.append("    " + ", ".join(str(v) for v in samples[i:i + 20]) + ",")
        out.append("};")
        out.append(f"static const int {name}DrawStartsMs[] = {{{', '.join(str(round(s * 1000)) for s in starts)}}};")
        out.append("")
        entries.append(f'    {{"{name}", {name}Tenths, {len(samples)}, {name}DrawStartsMs, {len(starts)}}},')
    out.append("static const RecordedShot recordedShots[] = {")
    out.extend(entries)
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
