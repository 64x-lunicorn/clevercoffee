"""Turns the logged shots (data/shot*.jsonl, 1 Hz) into a C header for the native
brew-detection and core tests: sensor readings sample-and-hold resampled to the firmware's
400 ms interval, in 1/10 °C, plus for every water draw its start time and the expected shot
start/end taken from the 1 Hz log (start: first sample below the top of the drop, end: first
sample at the lowest temperature within 70 s, i.e. the moment the fall stops).

    python3 gen_test_vectors.py > ../../test/test_brew_detection/recorded_shots.h
"""
import sys
from pathlib import Path

from test_brew_detection import SAMPLE_S, load, shot_starts

HERE = Path(__file__).parent


def expected_shot(series, draw_start):
    """(start, end) of the shot around a draw found by shot_starts(), in log seconds"""
    i = next(k for k, (t, _) in enumerate(series) if t >= draw_start)
    while i > 0 and series[i - 1][1] > series[i][1]:  # walk up to the top of the drop
        i -= 1
    while i + 1 < len(series) and series[i + 1][1] >= series[i][1]:  # flat top: last sample on it
        i += 1
    start = series[i + 1][0]
    window = [(t, temp) for t, temp in series if start <= t <= start + 70]
    low = min(temp for _, temp in window)
    end = min(t for t, temp in window if temp == low)
    return start, end


def main():
    out = ["// generated by tools/silvia-sim/gen_test_vectors.py - do not edit", "#pragma once", "",
           "struct RecordedShot {", "    const char *name;", "    const short *tenths;  // one reading every 400 ms",
           "    int count;", "    const int *drawStartsMs;", "    int drawCount;",
           "    const int *expectedStartMs;  // shot start/end from the 1 Hz log, per draw",
           "    const int *expectedEndMs;", "};", ""]
    entries = []
    for path in sorted((HERE / "data").glob("shot*.jsonl")):
        series = load(path)
        starts = shot_starts(series)
        samples = []
        j = 0
        t = 0.0
        while t <= series[-1][0]:
            while j + 1 < len(series) and series[j + 1][0] <= t:
                j += 1
            samples.append(round(series[j][1] * 10))
            t += SAMPLE_S
        name = path.stem
        out.append(f"static const short {name}Tenths[] = {{")
        for i in range(0, len(samples), 20):
            out.append("    " + ", ".join(str(v) for v in samples[i:i + 20]) + ",")
        out.append("};")
        out.append(f"static const int {name}DrawStartsMs[] = {{{', '.join(str(round(s * 1000)) for s in starts)}}};")
        bounds = [expected_shot(series, s) for s in starts]
        out.append(f"static const int {name}ExpectedStartMs[] = {{{', '.join(str(round(b[0] * 1000)) for b in bounds)}}};")
        out.append(f"static const int {name}ExpectedEndMs[] = {{{', '.join(str(round(b[1] * 1000)) for b in bounds)}}};")
        out.append("")
        entries.append(f'    {{"{name}", {name}Tenths, {len(samples)}, {name}DrawStartsMs, {len(starts)}, '
                       f'{name}ExpectedStartMs, {name}ExpectedEndMs}},')
    out.append("static const RecordedShot recordedShots[] = {")
    out.extend(entries)
    out.append("};")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
